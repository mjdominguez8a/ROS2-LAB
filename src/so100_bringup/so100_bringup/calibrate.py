"""Record servo offsets for one SO-100 (robot NOT running in ROS).

    ros2 run so100_bringup calibrate --robot-id arm3 [--port /dev/so100]

1. Torque is switched off so you can move the arm by hand.
2. Put the arm in the ZERO pose (all joints at 0 rad - compare with RViz:
   `ros2 launch so100_bringup arm.launch.py` shows it at startup).
3. Press Enter: the raw servo positions are saved as offsets to
   src/so100_bringup/config/robots/<robot-id>.yaml. Rebuild (`cb`) afterwards.
"""
import argparse
import os
import sys

import yaml

BAUD = 1_000_000
ADDR_TORQUE_ENABLE = 40
ADDR_PRESENT_POSITION = 56
JOINTS = ['shoulder_pan_joint', 'shoulder_lift_joint', 'elbow_flex_joint',
          'wrist_flex_joint', 'wrist_roll_joint', 'gripper_joint']


def _packet(servo_id, instruction, params):
    body = [servo_id, len(params) + 2, instruction, *params]
    return bytes([0xFF, 0xFF, *body, (~sum(body)) & 0xFF])


def write_byte(port, servo_id, addr, value):
    port.reset_input_buffer()
    port.write(_packet(servo_id, 0x03, [addr, value]))
    port.read(6)  # status packet


def read_word(port, servo_id, addr):
    port.reset_input_buffer()
    port.write(_packet(servo_id, 0x02, [addr, 2]))
    reply = port.read(8)  # FF FF id len err lo hi chk
    if len(reply) != 8 or reply[0:2] != b'\xff\xff' or reply[2] != servo_id:
        raise IOError(f'No valid reply from servo {servo_id} (got {reply.hex()})')
    if reply[4] != 0:
        print(f'  warning: servo {servo_id} reports error flags {reply[4]:#04x}')
    return reply[5] | (reply[6] << 8)


def main():
    import serial  # python3-serial

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument('--robot-id', required=True)
    ap.add_argument('--port', default='/dev/so100')
    args = ap.parse_args()

    here = os.path.dirname(os.path.realpath(__file__))
    template = os.path.join(here, '..', 'config', 'robots', 'default.yaml')
    out_dir = os.path.join(here, '..', 'config', 'robots')
    with open(template) as f:
        cal = yaml.safe_load(f)
    if not os.path.exists(args.port):
        print(f'Robot not found at {args.port}. Check USB/power (see docs/REAL_ROBOT.md).')
        return 1

    with serial.Serial(args.port, BAUD, timeout=0.05) as port:
        for name in JOINTS:
            write_byte(port, cal['joints'][name]['id'], ADDR_TORQUE_ENABLE, 0)
        print('Torque is OFF. Move the arm into the ZERO pose (see RViz), then press Enter.')
        input()
        for name in JOINTS:
            sid = cal['joints'][name]['id']
            raw = read_word(port, sid, ADDR_PRESENT_POSITION)
            cal['joints'][name]['offset'] = int(raw)
            print(f'  {name:22s} id={sid}  offset={raw}')

    cal['robot_id'] = args.robot_id
    path = os.path.normpath(os.path.join(out_dir, f'{args.robot_id}.yaml'))
    with open(path, 'w') as f:
        f.write('# Generated by `ros2 run so100_bringup calibrate`\n')
        yaml.safe_dump(cal, f, sort_keys=False)
    print(f'\nSaved {path}\nNow run `cb`, then: '
          f'ros2 launch so100_bringup arm.launch.py backend:=real robot:={args.robot_id}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
